"""
Roof ornament details for Tang-style buildings:
- Chiwei (鸱吻) at roof ridge ends
- Ridge beasts along main ridge
- Eave tile fringe using slabs
- Pagoda finials

Targets are described as (name, ridge_x1, ridge_z1, ridge_x2, ridge_z2, ridge_y).
For a north-south ridge x1==x2; for an east-west ridge z1==z2.
"""


def add_chiwen(fills: list[Fill], name: str, x: int, y: int, z: int, facing: str) -> None:
    """Add a chiwei (ridge-end guardian beast)."""
    if facing in ("n", "s"):
        add_fill(fills, f"{name} chiwen body", (x - 3, y, z - 2), (x + 3, y + 6, z + 2), M.GOLD)
        add_fill(fills, f"{name} chiwen head", (x - 2, y + 4, z - 4), (x + 2, y + 8, z - 1), M.GOLD)
        add_fill(fills, f"{name} chiwen tail", (x - 2, y + 2, z + 1), (x + 2, y + 5, z + 5), M.GOLD)
    else:
        add_fill(fills, f"{name} chiwen body", (x - 2, y, z - 3), (x + 2, y + 6, z + 3), M.GOLD)
        add_fill(fills, f"{name} chiwen head", (x - 4, y + 4, z - 2), (x - 1, y + 8, z + 2), M.GOLD)
        add_fill(fills, f"{name} chiwen tail", (x + 1, y + 2, z - 2), (x + 5, y + 5, z + 2), M.GOLD)


def add_ridge_beasts(fills: list[Fill], name: str, x1: int, z1: int, x2: int, z2: int, y: int) -> None:
    """Add small golden beasts along the central ridge."""
    if x1 == x2:
        # Ridge runs north-south
        for z in range(min(z1, z2) + 20, max(z1, z2) - 15, 30):
            add_fill(fills, f"{name} beast {z}", (x1 - 1, y, z - 1), (x1 + 1, y + 2, z + 1), M.GOLD)
    else:
        for x in range(min(x1, x2) + 20, max(x1, x2) - 15, 30):
            add_fill(fills, f"{name} beast {x}", (x - 1, y, z1 - 1), (x + 1, y + 2, z1 + 1), M.GOLD)


def add_eave_tiles(fills: list[Fill], name: str, x1: int, z1: int, x2: int, z2: int, y: int) -> None:
    """Add a fringe of alternating roof tiles along the eave edge."""
    if abs(x2 - x1) > abs(z2 - z1):
        # Long edge along x
        for x in range(min(x1, x2) + 2, max(x1, x2) - 1, 4):
            add_fill(fills, f"{name} eave tile {x}", (x, y, z1), (x + 1, y, z1 + 1), M.ROOF_GREEN_SLAB if x % 8 == 0 else M.ROOF_BLUE_SLAB)
            add_fill(fills, f"{name} eave tile s {x}", (x, y, z2 - 1), (x + 1, y, z2), M.ROOF_GREEN_SLAB if x % 8 == 0 else M.ROOF_BLUE_SLAB)
    else:
        for z in range(min(z1, z2) + 2, max(z1, z2) - 1, 4):
            add_fill(fills, f"{name} eave tile {z}", (x1, y, z), (x1 + 1, y, z + 1), M.ROOF_GREEN_SLAB if z % 8 == 0 else M.ROOF_BLUE_SLAB)
            add_fill(fills, f"{name} eave tile e {z}", (x2 - 1, y, z), (x2, y, z + 1), M.ROOF_GREEN_SLAB if z % 8 == 0 else M.ROOF_BLUE_SLAB)


def add_roof_ornament_set(
    fills: list[Fill],
    name: str,
    x1: int,
    z1: int,
    x2: int,
    z2: int,
    y: int,
) -> None:
    """Add ridge beasts, chiwei, and eave tiles for one roof ridge."""
    add_ridge_beasts(fills, name, x1, z1, x2, z2, y)
    if x1 == x2:
        # North-south ridge: chiwei at north and south ends
        add_chiwen(fills, name + " n", x1, y, min(z1, z2) + 4, "n")
        add_chiwen(fills, name + " s", x1, y, max(z1, z2) - 4, "s")
    else:
        # East-west ridge: chiwei at west and east ends
        add_chiwen(fills, name + " w", min(x1, x2) + 4, y, z1, "w")
        add_chiwen(fills, name + " e", max(x1, x2) - 4, y, z1, "e")
    add_eave_tiles(fills, name, x1 - 4, z1 - 4, x2 + 4, z2 + 4, y - 1)


