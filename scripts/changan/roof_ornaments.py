def build_roof_ornaments(fills: list[Fill]) -> None:
    for name, x1, z1, x2, z2, y in ROOF_TARGETS:
        add_roof_ornament_set(fills, name, x1, z1, x2, z2, y)

    for name, cx, cy, cz in PAGODA_FINIALS:
        add_fill(fills, f"{name} finial", (cx - 2, cy, cz - 2), (cx + 2, cy + 5, cz + 2), M.GOLD)


def main() -> None:
    run_builder(build_roof_ornaments, "roof_ornaments")


